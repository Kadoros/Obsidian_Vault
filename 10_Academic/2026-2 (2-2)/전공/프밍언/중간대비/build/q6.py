def dyn(chain):
    decl={"main":["a","b","c"],"sub1":["b","d"],"sub2":["c","d","e"],"sub3":["a","e","f"]}
    seen=[]; out=[]
    for fn in reversed(chain):
        for v in decl[fn]:
            if v not in seen: seen.append(v); out.append(f"{v}({fn})")
    return ", ".join(out)
